const {app,BrowserWindow}=require('electron')
const fs=require('node:fs'),path=require('node:path')
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('disable-gpu')
app.commandLine.appendSwitch('disable-gpu-compositing')
app.commandLine.appendSwitch('disable-gpu-sandbox')
app.commandLine.appendSwitch('in-process-gpu')
app.commandLine.appendSwitch('use-angle','swiftshader')
app.setPath('userData',path.resolve('preview/esports/check-profile-'+process.pid))
const samples=JSON.parse(fs.readFileSync('preview/esports/live-check.json','utf8'))
const delay=ms=>new Promise(r=>setTimeout(r,ms))
app.whenReady().then(async()=>{
    let win
    try {
        win=new BrowserWindow({show:false,width:1440,height:900,useContentSize:true,webPreferences:{offscreen:true,backgroundThrottling:false}})
        win.webContents.on('console-message',(_,level,text)=>{if(level>=2)console.error('Browser:',text)})
        await win.webContents.session.clearStorageData({storages:['localstorage']})
        await win.loadURL(`http://127.0.0.1:${process.env.ESPORTS_DEV_PORT || 5176}/__esports?fixture#/entertainment`)
        const run=code=>win.webContents.executeJavaScript(code)
        const assert=(v,msg)=>{if(!v)throw Error(msg)}
        const wait=async code=>{for(let i=0;i<150;i++){if(await run(`Boolean(${code})`))return;await delay(100)}throw Error('Timeout: '+code)}
        const click=async text=>{await run(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent.trim()===${JSON.stringify(text)}).click()`);await delay(200)}
        const shot=async name=>{
            await wait(`!document.querySelector('.es-spin')`)
            await run(`Promise.race([Promise.all(Array.from(document.images).filter(img=>!img.complete&&img.getBoundingClientRect().top<innerHeight).map(img=>new Promise(resolve=>{img.addEventListener('load',resolve,{once:true});img.addEventListener('error',resolve,{once:true})}))),new Promise(resolve=>setTimeout(resolve,2000))]).then(()=>undefined)`)
            await run(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve(true))))`)
            await delay(300)
            fs.writeFileSync(path.resolve('preview/esports/'+name+'.png'),(await win.webContents.capturePage()).toPNG())
        }
        const navigate=async url=>{await run(`router.push(${JSON.stringify(url)})`);await delay(150);await wait(`!document.querySelector('.es-spin') && !document.querySelector('.es-state')?.textContent.includes('加载')`)}
        const noOverflow=async()=>{const layout=await run(`({w:innerWidth,body:document.body.scrollWidth,page:document.querySelector('.es-page').scrollWidth,client:document.querySelector('.es-page').clientWidth})`);assert(layout.body<=layout.w&&layout.page<=layout.client+1,'Horizontal overflow '+JSON.stringify(layout))}
        await wait(`document.querySelectorAll('.es-match-row').length>0`)
        await shot('overview-desktop')
        await click('排行榜');await wait(`document.querySelectorAll('.es-table tbody tr').length>0`);await shot('ranking-desktop')
        assert(await run(`/5EPlay VRS|Valve Regional Standings/.test(document.querySelector('.es-ranking-attribution').textContent)`),'Official VRS attribution missing')
        const vrsPoints=await run(`document.querySelector('.es-rank-points').textContent`)
        await click('HLTV 排名');await wait(`!document.querySelector('.es-ranking-attribution') && document.querySelector('.es-rank-points')`)
        assert(await run(`document.querySelector('.es-rank-points').textContent`)!==vrsPoints,'VRS and HLTV use the same points')
        assert(await run(`calls.some(c=>c.operation==='ranking'&&c.params.source==='hltv')`),'HLTV source not requested')
        await shot('hltv-desktop');await click('VRS 排名')
        await click('赛事');await wait(`document.querySelectorAll('.es-tournament-card').length>0`);await delay(600);await shot('tournaments-desktop')
        await run(`document.querySelector('.es-card-favorite').click()`)
        assert(await run(`document.querySelector('.es-card-favorite').getAttribute('aria-pressed')==='true'`),'Tournament favorite failed')
        await click('我的收藏');assert(await run(`document.querySelectorAll('.es-tournament-card').length===1`),'Favorites filter failed')
        await click('全部');await click('系列赛');await wait(`document.querySelectorAll('.es-placement').length>0`);await shot('series-desktop')
        await click('赛果');await wait(`document.querySelectorAll('.es-match-row').length>0`)
        await run(`document.querySelector('.es-match-row').click()`);await wait(`document.querySelector('.es-radar')`);await delay(600);await shot('analysis-desktop')
        const initialPlayer=await run(`document.querySelector('.es-duel-player>b').textContent`)
        await run(`document.querySelectorAll('.es-player-strip button')[1].click()`)
        assert(await run(`document.querySelector('.es-duel-player>b').textContent`)!==initialPlayer,'Player comparison did not change')
        await click('PICK');assert(await run(`document.querySelector('.es-map-comparison').textContent.includes('次')`),'Map pick mode failed')
        await click('BAN');await click('胜率')
        await click('比赛数据');await wait(`document.querySelectorAll('.es-table tbody tr').length>0`)
        assert(await run(`document.querySelectorAll('.es-table tbody tr').length>=10`),'Full match player stats missing')
        await shot('match-desktop')
        await run(`document.querySelectorAll('.es-map-tabs button')[1].click()`);await delay(150)
        assert(await run(`!!document.querySelector('.es-round-strip')`),'Map round display missing')
        await click('实时播报');await wait(`document.querySelectorAll('.es-log-list li').length>0`);await shot('broadcast-desktop')
        const before=await run(`document.querySelectorAll('.es-log-list li').length`)
        await run(`document.querySelector('.es-toolbar .es-icon-btn').click()`);await delay(200)
        assert(await run(`document.querySelectorAll('.es-log-list li').length` )===before,'Duplicate broadcast entries')
        await click('分析');await delay(150)
        assert(await run(`document.querySelectorAll('.es-match-row').length>0`),'Recent matches missing')
        await run(`document.querySelector('.es-event-link').click()`);await wait(`document.querySelectorAll('.es-match-row').length>0`)
        await shot('event-desktop')
        await click('赛事统计');await wait(`document.querySelectorAll('.es-table tbody tr').length>0`)
        await click('名次 / 奖金');await wait(`document.querySelectorAll('.es-placement').length>0`);await shot('placements-desktop')
        await click('比赛地图');assert(await run(`document.querySelectorAll('.es-event-map').length>0`),'Event maps missing')
        await navigate('/entertainment?game=val&tab=ranking');await wait(`document.querySelectorAll('.es-table tbody tr').length>0`);await click('选手');await wait(`document.querySelectorAll('.es-table tbody tr').length>0`)
        await shot('val-ranking-desktop')
        const liveId=samples['csgo-live-detail'].match.mc_info.id
        await navigate('/entertainment/csgo/match/'+liveId);await click('VRS 预测');await shot('prediction-desktop')
        assert(await run(`document.querySelector('.es-detail-content .es-prediction').textContent.includes('5EPlay')`),'Prediction source missing')
        await run(`document.querySelectorAll('.es-detail-tabs button')[4].click()`);await delay(200)
        assert(await run(`!!document.querySelector('.es-video-start')`),'Live sources missing')
        await shot('live-desktop')
        await run(`document.querySelector('.es-video-start').click()`);await delay(500)
        assert(await run(`!!document.querySelector('.es-video iframe')`),'Web live player missing')
        await run(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent.includes('停止播放')).click()`)
        assert(await run(`!document.querySelector('.es-video iframe')`),'Live player failed to unmount')
        for(const [url,name] of [['/entertainment','overview-mobile'],['/entertainment?tab=ranking','ranking-mobile'],['/entertainment?tab=event','tournaments-mobile'],['/entertainment?tab=series','series-mobile'],['/entertainment/csgo/match/'+samples['csgo-detail'].match.mc_info.id,'match-mobile'],['/entertainment/val/event/'+samples['val-event'].basic.tt_id,'event-mobile']]) {
            win.setContentSize(390,844);await navigate(url);await delay(250)
            await noOverflow()
            await shot(name)
        }
        win.setContentSize(320,750);await navigate('/entertainment?tab=event');await noOverflow()
        await navigate('/entertainment?tab=ranking');await noOverflow()
        await navigate('/entertainment/csgo/match/'+samples['csgo-detail'].match.mc_info.id);await noOverflow()
        win.setContentSize(390,844)
        await navigate('/entertainment/csgo/match/'+samples['csgo-detail'].match.mc_info.id);await click('实时播报');await delay(5200)
        await navigate('/entertainment');const count=await run(`calls.filter(c=>c.operation==='logs'||c.operation==='detail').length`);await delay(5500)
        assert(await run(`calls.filter(c=>c.operation==='logs'||c.operation==='detail').length` )===count,'Detail polling still active after navigation')
        console.log('PASS: desktop/390px/320px layouts, real VRS/HLTV switch, CS/VAL rankings, favorites, series placements, player selection, map win/pick/ban, full statistics, broadcast deduplication, prediction attribution, live source rendering/unmount, polling cleanup')
        win.destroy();app.exit(0)
    } catch(error) {
        console.error(error)
        if(win && !win.isDestroyed()) {
            console.error(await win.webContents.executeJavaScript(`JSON.stringify({url:location.href,ready:window.ready,calls:window.calls,body:document.body.innerText.slice(0,5000)})`).catch(String))
            fs.writeFileSync(path.resolve('preview/esports/check-failure.png'),(await win.webContents.capturePage()).toPNG())
        }
        win?.destroy();app.exit(1)
    }
})
